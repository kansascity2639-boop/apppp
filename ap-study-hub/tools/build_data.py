#!/usr/bin/env python3
"""Validate the course content in content/*.py and write public/js/data.js.

Run from the project root:  python3 tools/build_data.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "content"))

import calc_ab, calc_bc, physics_1, chemistry, psychology, apush, world_history  # noqa: E402

COURSES = [calc_ab.COURSE, calc_bc.COURSE, physics_1.COURSE, chemistry.COURSE, psychology.COURSE, apush.COURSE, world_history.COURSE]
MATH_COURSES = {"calc-ab", "calc-bc", "physics-1", "chemistry"}

SHARED_RESOURCES = [
    {"title": "2027 AP Exam Dates", "url": "https://apstudents.collegeboard.org/exam-dates", "desc": "The official schedule for every AP exam."},
    {"title": "Bluebook: AP Exams", "url": "https://bluebook.collegeboard.org/students/ap-exams", "desc": "Install Bluebook, run the practice test, and learn how exam day works in the app."},
    {"title": "What to bring on exam day", "url": "https://apstudents.collegeboard.org/exam-policies-guidelines/what-to-bring-on-exam-day", "desc": "The official checklist of what to bring and what to leave at home."},
]

errors = []


def balance_answers(course):
    """Deterministically reorder choices so correct answers are spread evenly over A-D.
    Authors can write the correct answer anywhere; students never see a pattern."""
    import random
    rng = random.Random("ap-study-hub:" + course["id"])
    targets = [i % 4 for i in range(len(course["mcq"]))]
    rng.shuffle(targets)
    for q, t in zip(course["mcq"], targets):
        others = [i for i in range(len(q["choices"])) if i != q["answer"]]
        rng.shuffle(others)
        order = others[:t] + [q["answer"]] + others[t:]  # order[new_position] = old_index
        q["choices"] = [q["choices"][o] for o in order]
        q["notes"] = {order.index(int(k)): v for k, v in q.get("notes", {}).items()}
        q["answer"] = t


for c in COURSES:
    balance_answers(c)


def err(msg):
    errors.append(msg)


ids = set()
for c in COURSES:
    unit_ids = {u["id"] for u in c["units"]}
    c["math"] = c["id"] in MATH_COURSES
    for q in c["mcq"]:
        where = f'{c["id"]}/{q["id"]}'
        if q["id"] in ids:
            err(f"duplicate id {where}")
        ids.add(q["id"])
        if q["unit"] not in unit_ids:
            err(f"{where}: unknown unit {q['unit']}")
        if len(q["choices"]) != 4:
            err(f"{where}: needs exactly 4 choices")
        if len(set(q["choices"])) != len(q["choices"]):
            err(f"{where}: duplicate choices")
        if not 0 <= q["answer"] < len(q["choices"]):
            err(f"{where}: answer index out of range")
        notes = q.get("notes", {})
        for k in notes:
            if not 0 <= int(k) < len(q["choices"]):
                err(f"{where}: note index {k} out of range")
            if int(k) == q["answer"]:
                err(f"{where}: note attached to the correct answer")
        q["notes"] = {str(k): v for k, v in notes.items()}
        if not q.get("explain"):
            err(f"{where}: missing explanation")
    for f in c["frq"]:
        where = f'{c["id"]}/{f["id"]}'
        if f["id"] in ids:
            err(f"duplicate id {where}")
        ids.add(f["id"])
        for u in f["unit"]:
            if u not in unit_ids:
                err(f"{where}: unknown unit {u}")
        total = 0
        for p in f["parts"]:
            if len(p["rubric"]) != p["points"]:
                err(f"{where}({p['label']}): {p['points']} points but {len(p['rubric'])} rubric lines")
            total += p["points"]
        f["totalPoints"] = total
    for card in c["flashcards"]:
        if card["unit"] not in unit_ids:
            err(f'{c["id"]} flashcard "{card["front"][:30]}": unknown unit')
    for r in c["resources"]:
        if not r["url"].startswith("https://"):
            err(f'{c["id"]} resource {r["title"]}: not https')

if errors:
    print("Content errors:\n  " + "\n  ".join(errors))
    sys.exit(1)

out = ROOT / "public" / "js" / "data.js"
payload = {"courses": COURSES, "sharedResources": SHARED_RESOURCES}
out.write_text(
    "// Generated by tools/build_data.py from content/*.py. Edit the content files, not this file.\n"
    "window.HUB_DATA = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)
for c in COURSES:
    print(f'{c["short"]:<14} {len(c["mcq"]):>3} MCQ  {len(c["frq"]):>2} FRQ/SAQ  {len(c["flashcards"]):>3} cards  {len(c["resources"]):>2} resources')
print(f"Wrote {out.relative_to(ROOT)}")
